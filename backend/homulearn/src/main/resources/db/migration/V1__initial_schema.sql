create table users (
    id bigint generated by default as identity primary key,
    public_id uuid not null unique,
    email varchar(255) not null unique,
    password_hash varchar(255) not null,
    full_name varchar(255),
    role varchar(255) default 'STUDENT',
    status varchar(255) default 'ACTIVE',
    created_at timestamp
);
create unique index users_email_lower_unique on users (lower(email));

-- Preserve the existing prototype entity mappings; feature migrations follow later.
create table notes (
    id bigint generated by default as identity primary key,
    user_id bigint references users(id), title varchar(255), content text,
    created_at timestamp, updated_at timestamp
);
create index notes_user_updated on notes(user_id, updated_at desc);
create table decks (
    id bigint generated by default as identity primary key,
    user_id bigint references users(id), name varchar(255), created_at timestamp
);
create table cards (
    id bigint generated by default as identity primary key,
    deck_id bigint references decks(id), front text, back text,
    next_review_date timestamp, interval_days integer
);
create table goals (
    id bigint generated by default as identity primary key,
    user_id bigint references users(id), title varchar(255), current_progress integer,
    target_value integer, deadline timestamp, created_at timestamp
);
create table pomodoro_sessions (
    id bigint generated by default as identity primary key,
    user_id bigint references users(id), duration_minutes integer, completed_at timestamp
);
create table posts (
    id bigint generated by default as identity primary key,
    user_id bigint references users(id), title varchar(255), content text, created_at timestamp
);
create table reports (
    id bigint generated by default as identity primary key,
    reported_by bigint references users(id), target_type varchar(255), target_id bigint,
    reason text, status varchar(255), created_at timestamp
);
create table study_groups (
    id bigint generated by default as identity primary key,
    name varchar(255), description text, created_by bigint references users(id), created_at timestamp
);
create table tasks (
    id bigint generated by default as identity primary key,
    user_id bigint references users(id), title varchar(255), due_date timestamp,
    is_completed boolean, created_at timestamp
);
